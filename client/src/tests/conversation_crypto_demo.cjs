(async () => {
  const assert = require('node:assert/strict');
  const { webcrypto, createPublicKey, verify } = require('node:crypto');
  global.window = { crypto: webcrypto };
  global.crypto = webcrypto;
  const pins = new Map();
  global.localStorage = { getItem: key => pins.get(key) || null, setItem: (key, value) => pins.set(key, value) };
  const { deriveConversationKeyFromPrivate, identityFingerprint, pinPeerIdentity } = await import('../crypto/KeyExchange/conversationKey.js');
  const pair = () => webcrypto.subtle.generateKey({ name: 'ECDH', namedCurve: 'P-256' }, false, ['deriveBits']);
  const [alice, bob, attacker] = await Promise.all([pair(), pair(), pair()]);
  const b64 = async key => Buffer.from(await webcrypto.subtle.exportKey('raw', key)).toString('base64');
  const alicePublic = await b64(alice.publicKey);
  const bobPublic = await b64(bob.publicKey);
  const attackerPublic = await b64(attacker.publicKey);
  const aliceKey = await deriveConversationKeyFromPrivate({ localUsername: 'alice', peerUsername: 'bob', privateKey: alice.privateKey, peerAgreementPublicKey: bobPublic });
  const bobKey = await deriveConversationKeyFromPrivate({ localUsername: 'bob', peerUsername: 'alice', privateKey: bob.privateKey, peerAgreementPublicKey: alicePublic });
  const attackerKey = await deriveConversationKeyFromPrivate({ localUsername: 'mallory', peerUsername: 'alice', privateKey: attacker.privateKey, peerAgreementPublicKey: alicePublic });
  const iv = webcrypto.getRandomValues(new Uint8Array(12));
  const aad = new TextEncoder().encode('chat_alice_bob');
  const ciphertext = await webcrypto.subtle.encrypt({ name: 'AES-GCM', iv, additionalData: aad }, aliceKey, new TextEncoder().encode('secret'));
  assert.equal(new TextDecoder().decode(await webcrypto.subtle.decrypt({ name: 'AES-GCM', iv, additionalData: aad }, bobKey, ciphertext)), 'secret');
  await assert.rejects(() => webcrypto.subtle.decrypt({ name: 'AES-GCM', iv, additionalData: aad }, attackerKey, ciphertext));
  const identity = { signingPublicKey: Buffer.alloc(91, 1).toString('base64'), agreementPublicKey: bobPublic };
  const fingerprint = await identityFingerprint(identity);
  pinPeerIdentity('bob', fingerprint);
  const changed = await identityFingerprint({ ...identity, agreementPublicKey: attackerPublic });
  assert.throws(() => pinPeerIdentity('bob', changed), /identity key changed/);
  const signing = await webcrypto.subtle.generateKey({ name: 'ECDSA', namedCurve: 'P-256' }, false, ['sign', 'verify']);
  const signingPublicKey = Buffer.from(await webcrypto.subtle.exportKey('spki', signing.publicKey));
  const statement = Buffer.from(`securechat-identity-v1\u0000alice\u0000${alicePublic}`);
  const proof = Buffer.from(await webcrypto.subtle.sign({ name: 'ECDSA', hash: 'SHA-256' }, signing.privateKey, statement));
  assert.equal(verify('sha256', statement, { key: createPublicKey({ key: signingPublicKey, format: 'der', type: 'spki' }), dsaEncoding: 'ieee-p1363' }, proof), true);
  console.log('PASS: peers agree, outsider decryption fails, and changed peer keys are blocked.');
})().catch(error => { console.error(error); process.exitCode = 1; });
